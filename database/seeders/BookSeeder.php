    public function run(): void
    {
        if (Book::withTrashed()->exists()) {
            return;
        }

        $categories = Category::query()->pluck(column: 'id');
        $students = User::query()->where(column: 'role', operator: 'student')->pluck(column: 'id');
        $isPortuguese = app()->getLocale() === 'pt_BR';
        $faker = fake(locale: $isPortuguese ? 'pt_BR' : 'en_US');

        foreach ($this->realBooks as $bookIndex => $data) {
            $format = BookFormat::cases()[array_rand(array: BookFormat::cases())];
            $copies = $format === BookFormat::Digital ? 0 : random_int(min: 2, max: 12);

            $book = Book::query()->create([
                'title' => $data['title'],
                'author' => $data['author'],
                'publisher' => $data['publisher'],
                'year' => $data['year'] > 0 ? $data['year'] : null,
                'language' => $isPortuguese ? $data['language'] : 'en',
                'isbn' => $data['isbn'] ?? sprintf('978650%07d', $bookIndex + 1),
                'description' => $data['description'],
                'cover_path' => $data['cover_path'],
                'format' => $format,
                'total_copies' => $copies,
                'available_copies' => $copies,
                'loan_count' => random_int(min: 0, max: 120),
                'is_active' => true,
            ]);

            $book->categories()->sync($categories->random(random_int(min: 1, max: 2))->all());

            if ($format->isDigital()) {
                foreach (range(start: 1, end: random_int(min: 5, max: 15)) as $page) {
                    BookPage::query()->create([
                        'book_id' => $book->id,
                        'page_number' => $page,
                        'content' => $faker->paragraphs(nb: 8, asText: true),
                    ]);
                }
            }

            $studentCount = $students->count();

            if ($studentCount > 0) {
                foreach ($students->random(random_int(min: 1, max: min(8, $studentCount)))->all() as $userId) {
                    BookRating::query()->create([
                        'book_id' => $book->id,
                        'user_id' => $userId,
                        'rating' => random_int(min: 3, max: 5),
                    ]);
                }
            }
        }

        $sampleComments = $isPortuguese
            ? [
                'Adorei este livro. É uma leitura que fica na memória por muito tempo.',
                'A escrita exige atenção no começo, mas a história recompensa cada página.',
                'Recomendei para todo o meu grupo de leitura. Vale muito a pena.',
                'Comecei numa tarde chuvosa e não consegui parar de ler.',
                'Os personagens parecem reais. Continuei pensando neles dias depois.',
                'Uma leitura desafiadora, mas absolutamente recompensadora.',
                'O final me surpreendeu da melhor maneira possível.',
                'Reli vários trechos porque a escrita é muito bonita.',
            ]
            : [
                'Absolutely loved this book. It stays with you long after the last page.',
                'The writing takes some getting used to, but the story is deeply rewarding.',
                'I recommended this to everyone in my reading group. Incredible.',
                'Started this on a rainy afternoon and could not put it down.',
                'The characters felt incredibly real. I thought about them for days.',
                'A challenging read, but absolutely worth the effort.',
                'The ending surprised me in the best way possible.',
                'I reread several passages because they were beautifully written.',
            ];

        $sampleReplies = $isPortuguese
            ? [
                'Concordo totalmente com a sua leitura!',
                'Tive uma interpretação diferente, mas gostei da discussão.',
                'Obrigado por compartilhar. Seu comentário me deu vontade de ler.',
                'O estilo do autor é realmente único.',
            ]
            : [
                'I completely agree with your take!',
                'I had a different interpretation, but I enjoyed the discussion.',
                'Thanks for sharing. Your comment made me want to read it.',
                'The author has a truly unique style.',
            ];

        $users = User::query()->get();

        if ($users->isNotEmpty()) {
            foreach (Book::query()->inRandomOrder()->get() as $book) {
                if (random_int(1, 10) <= 3) {
                    continue;
                }

                foreach (range(1, random_int(1, 5)) as $unused) {
                    $commenter = $users->random();
                    $comment = BookComment::query()->create([
                        'book_id' => $book->id,
                        'user_id' => $commenter->id,
                        'body' => $sampleComments[array_rand($sampleComments)],
                    ]);
                    $this->seedVotes($comment, $users);

                    $replyCount = random_int(0, 2);
                    $parent = $comment;

                    for ($replyIndex = 0; $replyIndex < $replyCount; $replyIndex++) {
                        $otherUsers = $users->where('id', '!=', $commenter->id);
                        $replier = $otherUsers->isNotEmpty() ? $otherUsers->random() : $commenter;
                        $reply = BookComment::query()->create([
                            'book_id' => $book->id,
                            'user_id' => $replier->id,
                            'parent_id' => $parent->id,
                            'body' => $sampleReplies[array_rand($sampleReplies)],
                        ]);
                        $this->seedVotes($reply, $users);
                        $parent = $reply;
                    }
                }
            }
        }
    }

    /** @param \Illuminate\Database\Eloquent\Collection<int, User> $users */
    private function seedVotes(BookComment $comment, \Illuminate\Database\Eloquent\Collection $users): void
    {
        BookCommentVote::query()->create([
            'book_comment_id' => $comment->id,
            'user_id' => $comment->user_id,
            'value' => 1,
        ]);

        $otherUsers = $users->where('id', '!=', $comment->user_id);

        foreach ($otherUsers->random(min(random_int(0, 4), $otherUsers->count())) as $user) {
            BookCommentVote::query()->create([
                'book_comment_id' => $comment->id,
                'user_id' => $user->id,
                'value' => random_int(1, 5) === 1 ? -1 : 1,
            ]);
        }
    }
}
